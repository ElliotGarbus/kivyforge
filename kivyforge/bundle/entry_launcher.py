"""The launcher that calls a ``module:function`` entry point (issue #68).

An entry point written ``pkg.app:main``, in ``[tool.kivy].entry_point`` or as
the one ``[project.gui-scripts]`` entry, is called the way an installed script
calls it (the entry-points spec, "Use for scripts"): the module is imported, the
function is called with no arguments, and what it returns is the exit status.
pip's wrapper for ``myapp = "pkg.app:main"`` is, in substance::

    import sys
    from pkg.app import main
    sys.exit(main())

Every platform starts an app by running one module as ``__main__``. For this
form that module is the launcher rendered here, not ``pkg/app.py``. Run as
``__main__``, ``pkg/app.py`` would not be part of its package, so a relative
import inside it fails; imported by the launcher, it is ``pkg.app``, as under
``uv run``.

Desktop and Android write the launcher into the bundle's copy of ``app_dir``
(:func:`write_launcher`) before byte-compiling, so ``strip_source`` treats it
like the app's own modules and the import system finds it either way. iOS
cannot: a debug build's ``app/`` is a link to the user's source tree. It
embeds :func:`launcher_source` in ``main_config.h`` instead.

The bare form (``entry_point = "main"``) has no launcher: the module itself
runs as ``__main__``, exactly as before.
"""

from __future__ import annotations

from pathlib import Path

from ..config.model import KivyMeta

#: The module each platform runs as ``__main__`` for a ``module:function``
#: entry point. Underscored and kivyforge-named, so it cannot be an app module.
LAUNCHER_MODULE = "_kivyforge_main"


def main_module(kivy: KivyMeta) -> str:
    """The module a platform runs as ``__main__`` for this app."""
    return kivy.entry_point if kivy.entry_function is None else LAUNCHER_MODULE


def render_launcher(module: str, function: str) -> str:
    """The launcher source that calls *module*'s *function* (``obj.attr`` too).

    Both are checked identifiers by the time they get here (config rule 5), so
    inlining them is safe. The ``__name__`` guard is pip's, and it matters for
    the same reason: ``multiprocessing``'s spawn start method imports the main
    module again in every child, as ``__mp_main__``, and without the guard each
    child would start the app.

    pip ends in ``sys.exit(main())`` unconditionally; this raises
    ``SystemExit`` only for a status that is not success. The exit status is
    the same either way, since a ``__main__`` that ends normally exits 0. The
    difference is on Android: there an uncaught ``SystemExit`` becomes a
    process ``exit()`` on the SDL thread, which aborts in a UI thread
    (SIGABRT, measured on the x86_64 emulator, 2026-10-21) where a returning
    entry point ends cleanly. So an app that stops normally ends the way a
    ``"main"`` entry point does on every platform.
    """
    head = function.split(".")[0]
    return (
        "# Generated by kivyforge - do not edit.\n"
        f'"""Calls {module}:{function} as an installed gui-script would."""\n'
        "\n"
        "import sys\n"
        "\n"
        f"from {module} import {head}\n"
        "\n"
        'if __name__ == "__main__":\n'
        f"    _status = {function}()\n"
        "    if _status is not None and _status != 0:\n"
        "        sys.exit(_status)\n"
    )


def launcher_source(kivy: KivyMeta) -> str | None:
    """The launcher this app needs, or ``None`` for the bare-module form."""
    if kivy.entry_function is None:
        return None
    return render_launcher(kivy.entry_point, kivy.entry_function)


def write_launcher(app_dir: Path, kivy: KivyMeta) -> Path | None:
    """Write the launcher into a bundle's copy of ``app_dir``, if it needs one.

    Call it after the app's package metadata is installed, so ``top_level.txt``
    lists the app's modules and not kivyforge's, and before byte-compiling.
    """
    source = launcher_source(kivy)
    if source is None:
        return None
    dest = app_dir / f"{LAUNCHER_MODULE}.py"
    dest.write_text(source, encoding="utf-8")
    return dest


def missing_entry_module(src: Path, kivy: KivyMeta) -> str | None:
    """The file ``entry_point`` should be, relative to *src*, if it is missing.

    The bare form runs a module file, so it must be ``pkg/start.py``. The
    function form imports its module, which may be a package too
    (``pkg:main`` from ``pkg/__init__.py``).
    """
    rel = "/".join(kivy.entry_point.split("."))
    if (src / f"{rel}.py").is_file():
        return None
    if kivy.entry_function is not None and (src / rel / "__init__.py").is_file():
        return None
    return f"{rel}.py"


def missing_entry_message(app_dir: str, kivy: KivyMeta, rel: str) -> str:
    """The error for :func:`missing_entry_module`, naming where it was declared.

    The bare form's text is the one every desktop backend has always given.
    """
    detail = (
        ""
        if kivy.entry_function is None
        else f"{kivy.entry_spec}, from {kivy.entry_origin}; "
    )
    return (
        f"entry point {rel} not found in {app_dir}/ "
        f"({detail}set [tool.kivy].entry_point)."
    )

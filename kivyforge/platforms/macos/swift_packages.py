"""Build the locked Swift packages into the ``.app`` (#201).

macos-swift-packages-proposal §3.2, as the spike measured it
(macos-swift-packages-spike-findings.md). The macOS backend has no Xcode
project, so kivyforge writes a throwaway root package that depends on every
locked package and builds its one dynamic product with ``xcodebuild``:

- Products whose manifest leaves ``type`` unset link statically into
  ``KivyforgePackages.framework``, the framework Python loads. A product that
  declares ``type: .dynamic`` stays a framework of its own, which the root
  links by ``@rpath``; every framework ``xcodebuild`` writes is staged.
- ``LD_RUNPATH_SEARCH_PATHS=@loader_path/../../..`` gives each framework a run
  path to ``Contents/Frameworks/`` from its own ``Versions/A/``, so it finds the
  others whatever process loads it. ``xcodebuild`` gives them only
  ``/usr/lib/swift``.
- ``xcodebuild``, not ``swift build``: its ``Bundle.module`` looks in the main
  bundle's ``Contents/Resources/``, which codesign seals; ``swift build``'s
  looks at the top of the ``.app``, which it does not. Every
  ``<package>_<target>.bundle`` is staged there.
- ``-ObjC``: Python finds Swift classes through the Objective-C runtime by
  name. Package targets link as prelinked objects and keep their classes, but
  a static ``binaryTarget`` is an archive the linker would strip of classes
  and categories nothing references.

Built unsigned (``CODE_SIGNING_ALLOWED=NO``): the bundle's deep sign signs the
frameworks with everything else.
"""

from __future__ import annotations

import shutil
from collections.abc import Callable
from pathlib import Path
from typing import Protocol

import click

from kivyforge.lock.model import LockedSwiftPackage
from kivyforge.report import failures
from kivyforge.streaming import elapsed, run_streaming

from . import AppBundleError

#: The root package, its product, and the framework Python loads.
ROOT = "KivyforgePackages"
SWIFT_KEY = "[tool.kivy.macos.native.swift_packages]"
#: ``xcodebuild``'s Release products, under ``-derivedDataPath``.
_PRODUCTS = Path("Build") / "Products" / "Release"
_RPATH = "@loader_path/../../.."
#: Failure output kept in the error: the ``error:`` lines and the tail.
_TAIL = 25


class XcodebuildRunner(Protocol):
    def __call__(
        self, cmd: list[str], *, cwd: Path, echo: Callable[[str], None]
    ) -> tuple[int, str]:
        """Run *cmd*; return its exit status and output."""
        ...


def package_identity(sp: LockedSwiftPackage) -> str:
    """SwiftPM's identity for a package: the last URL or path component.

    ``.product(name:package:)`` names a package by it, not by the name its
    manifest declares nor the key in ``pyproject.toml``.
    """
    source = (sp.url or sp.path or "").rstrip("/")
    last = source.replace("\\", "/").rsplit("/", 1)[-1]
    if ":" in last:  # scp-like git@host:repo with no slash after the colon
        last = last.rsplit(":", 1)[-1]
    return last.removesuffix(".git").lower()


def render_manifest(
    packages: tuple[LockedSwiftPackage, ...],
    *,
    project_root: Path,
    minimum_system_version: str,
) -> str:
    """The root ``Package.swift``: every locked product in one dynamic library."""
    deps: list[str] = []
    products: list[str] = []
    for sp in sorted(packages, key=lambda s: s.name):
        if sp.url:
            if not sp.revision:
                raise AppBundleError(
                    f"swift package {sp.name!r} has no pinned revision in "
                    "pylock.macos.toml; re-run `kivyforge lock -p macos`.",
                    **failures.LOCK_UNREADABLE,
                )
            deps.append(
                f".package(url: {_swift_str(sp.url)}, "
                f"revision: {_swift_str(sp.revision)})"
            )
        else:
            assert sp.path is not None
            local = (project_root / sp.path).resolve()
            deps.append(f".package(path: {_swift_str(str(local))})")
        identity = package_identity(sp)
        products += [
            f".product(name: {_swift_str(p)}, package: {_swift_str(identity)})"
            for p in sp.products
        ]
    dep_lines = "".join(f"        {d},\n" for d in deps)
    product_lines = "".join(f"                {p},\n" for p in products)
    return (
        "// swift-tools-version:5.9\n"
        "// Generated by kivyforge from pylock.macos.toml; do not edit.\n"
        "import PackageDescription\n\n"
        "let package = Package(\n"
        f'    name: "{ROOT}",\n'
        f"    platforms: [.macOS({_swift_str(minimum_system_version)})],\n"
        f'    products: [.library(name: "{ROOT}", type: .dynamic, '
        f'targets: ["{ROOT}"])],\n'
        f"    dependencies: [\n{dep_lines}    ],\n"
        "    targets: [\n"
        "        .target(\n"
        f'            name: "{ROOT}",\n'
        f"            dependencies: [\n{product_lines}            ],\n"
        '            linkerSettings: [.unsafeFlags(["-Xlinker", "-ObjC"])]\n'
        "        ),\n"
        "    ]\n"
        ")\n"
    )


def xcodebuild_command(derived_data: Path, *, arch: str) -> list[str]:
    return [
        "xcodebuild",
        "-scheme",
        ROOT,
        "-destination",
        "generic/platform=macOS",
        "-configuration",
        "Release",
        "-derivedDataPath",
        str(derived_data),
        # A package's build-tool plug-ins and macros would otherwise wait for
        # a trust prompt that a command-line build cannot answer.
        "-skipPackagePluginValidation",
        "-skipMacroValidation",
        f"ARCHS={arch}",
        "ONLY_ACTIVE_ARCH=NO",
        "CODE_SIGNING_ALLOWED=NO",
        f"LD_RUNPATH_SEARCH_PATHS={_RPATH}",
        "build",
    ]


def build_swift_packages(
    packages: tuple[LockedSwiftPackage, ...],
    contents: Path,
    *,
    project_root: Path,
    work_dir: Path,
    arch: str,
    minimum_system_version: str,
    run: XcodebuildRunner | None = None,
    echo: Callable[[str], None] = click.echo,
) -> list[Path]:
    """Build *packages* and stage the result under *contents*; return what was placed.

    *work_dir* holds the root package and ``xcodebuild``'s derived data. It
    persists between builds, so package checkouts and compiled objects are
    reused; only its products are cleared, so a package dropped from the lock
    leaves nothing behind.
    """
    if not packages:
        return []
    for sp in packages:
        if sp.path and not (project_root / sp.path / "Package.swift").is_file():
            raise AppBundleError(
                f"swift package {sp.name!r}: {sp.path}/Package.swift does not "
                f"exist.\n  Fix the 'path' in {SWIFT_KEY}.",
                context={"package": sp.name, "path": sp.path},
            )
    manifest = render_manifest(
        packages,
        project_root=project_root,
        minimum_system_version=minimum_system_version,
    )
    try:
        sources = work_dir / "Sources" / ROOT
        sources.mkdir(parents=True, exist_ok=True)
        (sources / f"{ROOT}.swift").write_text(
            "// The products this framework links are its content.\n",
            encoding="utf-8",
        )
        (work_dir / "Package.swift").write_text(manifest, encoding="utf-8")
        derived = work_dir / "DerivedData"
        shutil.rmtree(derived / _PRODUCTS, ignore_errors=True)
    except OSError as exc:
        raise AppBundleError(
            failures.os_failure("write the Swift package build", exc)
        ) from exc

    names = ", ".join(sp.name for sp in sorted(packages, key=lambda s: s.name))
    echo(f"Building {len(packages)} Swift packages ({names}) with xcodebuild ...")
    cmd = xcodebuild_command(derived, arch=arch)
    try:
        returncode, transcript = (run or _run_xcodebuild)(cmd, cwd=work_dir, echo=echo)
    except OSError as exc:
        raise AppBundleError(
            f"could not run xcodebuild: {exc}.\n"
            "  Fix: install Xcode and select it with `xcode-select -s`; "
            "`kivyforge doctor -p macos` checks the setup.",
            **failures.spawn_failure("xcodebuild", exc),
        ) from exc
    if returncode != 0:
        raise AppBundleError(
            f"xcodebuild could not build the Swift packages in {SWIFT_KEY}.\n"
            f"{_excerpt(transcript)}\n"
            f"  The package it built is {work_dir / 'Package.swift'}.",
            **failures.build_tool_failed("xcodebuild", "build"),
        )
    return _stage(derived / _PRODUCTS, contents)


def _stage(products: Path, contents: Path) -> list[Path]:
    frameworks = sorted((products / "PackageFrameworks").glob("*.framework"))
    if not any(f.name == f"{ROOT}.framework" for f in frameworks):
        raise AppBundleError(
            "xcodebuild reported success but wrote no "
            f"{ROOT}.framework under {products}.\n"
            "  File a kivyforge issue with the build log.",
            **failures.ARTIFACT_MISSING,
        )
    bundles = sorted(products.glob("*.bundle"))
    placed: list[Path] = []
    for src, dest_dir in [
        *((f, contents / "Frameworks") for f in frameworks),
        *((b, contents / "Resources") for b in bundles),
    ]:
        dest = dest_dir / src.name
        if dest.exists():
            raise AppBundleError(
                f"a Swift package build wrote {src.name}, but the bundle "
                f"already has {dest.relative_to(contents.parent)}.\n"
                "  Rename the native binary or include_files entry that "
                "put it there.",
                context={"path": dest.relative_to(contents.parent).as_posix()},
            )
        try:
            dest_dir.mkdir(parents=True, exist_ok=True)
            # symlinks=True keeps a framework's Versions/Current links, which
            # codesign requires of a versioned bundle.
            shutil.copytree(src, dest, symlinks=True)
        except OSError as exc:
            raise AppBundleError(failures.os_failure(f"stage {src.name}", exc)) from exc
        placed.append(dest)
    return placed


def _run_xcodebuild(
    cmd: list[str], *, cwd: Path, echo: Callable[[str], None]
) -> tuple[int, str]:
    def segment(text: str) -> bool:
        line = text.strip()
        # Fetching is the slow part of a first build; compiling is not shown,
        # since xcodebuild prints several lines per file.
        if line.startswith(("Fetching from", "Resolved source packages")):
            echo(f"  xcodebuild: {line}")
            return True
        return False

    return run_streaming(
        cmd,
        cwd=cwd,
        on_segment=segment,
        on_quiet=lambda seconds: echo(
            f"  xcodebuild: still building ({elapsed(seconds)})"
        ),
    )


def _excerpt(transcript: str) -> str:
    lines = transcript.splitlines()
    errors = [line for line in lines if "error:" in line]
    shown = errors or lines[-_TAIL:]
    return "\n".join(f"    {line}" for line in shown[-_TAIL:])


def _swift_str(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'

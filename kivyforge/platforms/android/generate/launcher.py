"""The compile-time check of ``[tool.kivy.android].main_activity`` (android/04).

Android needs four things of a launcher class: it exists, it is a
``PythonActivity`` (so the bootstrap runs), it is concrete and public, and it
has a public no-argument constructor (the framework instantiates it by
reflection). One Java expression, ``PythonActivity x = new <configured>()``,
is exactly that set of facts, and javac decides each one with a message naming
the class. So the check is a generated file rather than a scan of the app's
sources: it holds wherever the class comes from (a ``src`` root, an
``include_files`` copy, a ``.aar``) and covers Kotlin, which javac sees in a
mixed module.

A failure is a Gradle compile failure (``KF-BUILD-TOOL-FAILED``, exit 5) with
the javac line in the log; the file's header says what that line means. The
class is package-private and unreferenced, so R8 drops it from a minified
release.
"""

from __future__ import annotations

from kivyforge.config.model import AndroidConfig

from ..bootstrap.render import RenderedFile

LAUNCHER_CHECK_NAME = "KivyforgeLauncherCheck.java"
LAUNCHER_CHECK_RELPATH = f"java/org/kivy/android/{LAUNCHER_CHECK_NAME}"


def render_launcher_check(android: AndroidConfig) -> RenderedFile | None:
    """The check for the configured launcher, or ``None`` when it is the
    generated ``PythonActivity`` (which needs no proof)."""
    if android.main_activity is None:
        return None
    source = (
        "// Generated by kivyforge; do not edit. Compiles only if\n"
        "// [tool.kivy.android].main_activity names a concrete public subclass of\n"
        "// PythonActivity with a public no-argument constructor. A javac error\n"
        "// on the `return` line below names the class and the property it lacks.\n"
        "package org.kivy.android;\n"
        "\n"
        "final class KivyforgeLauncherCheck {\n"
        "    private KivyforgeLauncherCheck() {}\n"
        "\n"
        "    static PythonActivity launcher() {\n"
        f"        return new {android.main_activity}();\n"
        "    }\n"
        "}\n"
    )
    return RenderedFile(LAUNCHER_CHECK_RELPATH, source)

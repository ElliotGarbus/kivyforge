"""``[tool.kivy.android.proguard]``: compose ``app/proguard-rules.pro`` (android/04).

The file is the kivyforge baseline, then the app's ``keep`` directives verbatim,
then each ``rules_files`` file in declared order, each block under a comment
naming where it came from, so a rule in a built project can be traced back to
what declared it. It is regenerated on every build and written the same way
whether or not ``minify`` is on: R8 reads it only when ``minifyEnabled`` is
true, so turning ``minify`` on changes only that Gradle flag.

``rules_files`` are pinned by SHA-256 in the lock, as ``include_files`` are:
``lock`` records the pins, ``build`` refuses a file that changed since, and a
re-run of ``lock`` re-records them without re-resolving anything. The paths are
deliberately not lock inputs (``kivyforge/lock/inputs.py``): nothing resolved
depends on them, and the pins already catch an added, removed or edited file.
"""

from __future__ import annotations

import dataclasses
from collections.abc import Iterable
from datetime import UTC, datetime
from pathlib import Path
from typing import TYPE_CHECKING

from kivyforge.artifacts.verify import sha256_file
from kivyforge.config.model import (
    ANDROID_BOOTSTRAP_NAMESPACES,
    AndroidProguardConfig,
    Config,
)
from kivyforge.report import diagnostics, exit_codes
from kivyforge.report.failures import ClassifiedError

from .lock.model import LockedRulesFile

if TYPE_CHECKING:
    from kivyforge.doctor.result import CheckResult

TABLE = "tool.kivy.android.proguard"

_HEADER = (
    "# Generated by kivyforge on every build: edits here are overwritten.\n"
    f"# Add rules with [{TABLE}] in pyproject.toml.\n"
)


class ProguardError(ClassifiedError):
    """A rules file could not be read or pinned."""


class RulesFileDrift(ProguardError):
    """A rules file differs from, lacks or outlives its pin."""

    code = diagnostics.LOCK_DRIFT
    exit_code = exit_codes.LOCK_DRIFT


def baseline() -> str:
    """The rules kivyforge always writes: the bootstrap and the JNI bridge."""
    return "".join(
        f"-keep class {namespace}.** {{ *; }}\n"
        for namespace in ANDROID_BOOTSTRAP_NAMESPACES
    )


def compose(proguard: AndroidProguardConfig, root: Path) -> str:
    """The whole ``app/proguard-rules.pro``, deterministic for a given input.

    A rules file's line endings are normalised to ``\\n`` and a UTF-8 BOM is
    dropped, so the same checkout generates the same file on every host.
    """
    blocks = [
        _HEADER,
        "# kivyforge baseline: pyjnius reflects into these at runtime.\n" + baseline(),
    ]
    if proguard.keep:
        blocks.append(
            f"# [{TABLE}].keep\n" + "".join(_line(rule) for rule in proguard.keep)
        )
    for source in proguard.rules_files:
        blocks.append(f"# [{TABLE}].rules_files: {source}\n" + _read(root, source))
    return "\n".join(blocks)


def _line(text: str) -> str:
    text = text.replace("\r\n", "\n")
    return text if text.endswith("\n") else text + "\n"


def _read(root: Path, source: str) -> str:
    path = root / source
    try:
        text = path.read_bytes().decode("utf-8-sig")
    except FileNotFoundError as exc:
        raise ProguardError(
            f"[{TABLE}].rules_files entry does not exist: {source}"
        ) from exc
    except UnicodeDecodeError as exc:
        raise ProguardError(
            f"[{TABLE}].rules_files entry {source} is not UTF-8 text, which is "
            "how R8 reads a rules file."
        ) from exc
    except OSError as exc:
        raise ProguardError(f"could not read {source}: {exc}") from exc
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    if text and not text.endswith("\n"):
        text += "\n"
    return text


# --- lock pins ---------------------------------------------------------------


def hash_pins(proguard: AndroidProguardConfig, root: Path) -> list[LockedRulesFile]:
    """One pin per declared rules file, sorted the way the lock writes them."""
    pins: dict[str, LockedRulesFile] = {}
    for source in proguard.rules_files:
        path = root / source
        if not path.is_file():
            raise ProguardError(
                f"[{TABLE}].rules_files entry does not exist: {source} "
                f"(resolved to {path.resolve()})"
            )
        pins[source] = LockedRulesFile(source=source, sha256=sha256_file(path))
    return sorted(pins.values(), key=lambda p: p.source)


def pins_current(
    pins: Iterable[LockedRulesFile], proguard: AndroidProguardConfig, root: Path
) -> bool:
    """Whether *pins* are exactly what :func:`hash_pins` would record now."""
    try:
        fresh = hash_pins(proguard, root)
    except ProguardError:
        return False
    return fresh == sorted(pins, key=lambda p: p.source)


def lock_current(lock, config: Config, root: Path) -> bool:
    """``include_files.lock_current`` for Android, plus the rules-file pins."""
    from kivyforge.artifacts import include_files

    return include_files.lock_current(lock, config, "android", root) and (
        pins_current(lock.proguard_rules_files, config.android_required.proguard, root)
    )


def refresh(lock, config: Config, *, project_root: Path, now: datetime | None = None):
    """*lock* with its rules-file pins re-hashed from disk, or *lock* itself."""
    pins = hash_pins(config.android_required.proguard, project_root.resolve())
    if pins == sorted(lock.proguard_rules_files, key=lambda p: p.source):
        return lock
    return dataclasses.replace(
        lock,
        proguard_rules_files=tuple(pins),
        generated_at=(now or datetime.now(UTC)).strftime("%Y-%m-%dT%H:%M:%SZ"),
    )


def pin_changes(
    old: Iterable[LockedRulesFile], new: Iterable[LockedRulesFile]
) -> list[str]:
    """``lock`` and ``lock --check`` lines for the pins that differ."""
    before = {p.source: p.sha256 for p in old}
    after = {p.source: p.sha256 for p in new}
    out: list[str] = []
    for source in sorted(before.keys() | after.keys()):
        if source not in before:
            change = "added"
        elif source not in after:
            change = "removed"
        elif before[source] != after[source]:
            change = "changed"
        else:
            continue
        out.append(f"  ~ proguard.rules_files: {source} ({change})")
    return out


def verify_pins(
    proguard: AndroidProguardConfig, pins: Iterable[LockedRulesFile], root: Path
) -> None:
    """Refuse an edited rules file, one with no pin, and a pin with no file."""
    recorded = {p.source: p.sha256 for p in pins}
    relock = "kivyforge lock -p android"
    for source in proguard.rules_files:
        sha256 = recorded.get(source)
        if sha256 is None:
            raise RulesFileDrift(
                f"proguard rules_files drift: {source} is declared but the lock "
                "records no hash for it.\n"
                f"  Re-run `{relock}` to record it.",
                context={"source": source},
            )
        path = root / source
        if not path.is_file():
            raise RulesFileDrift(
                f"proguard rules_files drift: {source} no longer exists.",
                context={"source": source},
            )
        actual = sha256_file(path)
        if actual != sha256:
            raise RulesFileDrift(
                f"proguard rules_files drift: {source} has changed since the "
                "lock was written.\n"
                f"  locked:  {sha256}\n"
                f"  on disk: {actual}\n"
                f"  Re-run `{relock}` to accept the new content.",
                context={"source": source},
            )
    stale = sorted(recorded.keys() - set(proguard.rules_files))
    if stale:
        raise RulesFileDrift(
            f"proguard rules_files drift: the lock records {', '.join(stale)}, "
            "which pyproject.toml no longer declares.\n"
            f"  Re-run `{relock}` to re-record the rules files.",
            context={"source": stale[0]},
        )


# --- doctor ------------------------------------------------------------------


def doctor_check(config: Config, root: Path, lock=None) -> CheckResult:
    """The "R8 keep rules" row of android/06's doctor table.

    FAIL on a ``rules_files`` entry that is missing or escapes the project;
    SKIP when ``minify`` is off or nothing Python could reach in Java is
    shipped; WARN when ``minify`` is on, such Java ships, and no rule is
    declared; WARN on rules-file drift against *lock*, which ``build``
    refuses. "Java Python could reach" is the app's own ``src`` and, beyond
    the spec's first wording, Maven dependencies and ``.aar``/``.jar``
    archives: R8 sees a library reached only through ``autoclass`` no better
    than the app's own classes.
    """
    from kivyforge.doctor.result import CheckResult, Status

    name = "R8 keep rules"
    android = config.android_required
    proguard = android.proguard
    for source in proguard.rules_files:
        resolved = (root / source).resolve()
        if not resolved.is_relative_to(root.resolve()):
            return CheckResult(
                name,
                Status.FAIL,
                f"rules_files entry escapes the project: {source}",
                hint="keep rules files inside the project directory.",
            )
        if not resolved.is_file():
            return CheckResult(
                name,
                Status.FAIL,
                f"rules_files entry does not exist: {source}",
                hint="fix the path; it is relative to the project root.",
            )
    if not android.build_settings.minify:
        return CheckResult(
            name, Status.SKIP, "minify is off; R8 does not run, so the rules are unused"
        )
    shipped = _java_python_may_reach(config)
    if not shipped:
        return CheckResult(
            name, Status.SKIP, "the app ships no Java beyond kivyforge's own"
        )
    if not proguard.declared:
        return CheckResult(
            name,
            Status.WARN,
            f"minify is on and the app ships {', '.join(shipped)}, but "
            f"[{TABLE}] declares no keep rules",
            hint="R8 removes or renames classes reached only from Python, and the "
            "release build then fails at run time with ClassNotFoundException. "
            f"Add -keep rules for them under [{TABLE}], and try "
            "`kivyforge run -p android --release`.",
        )
    if lock is not None:
        drifted = pin_changes(lock.proguard_rules_files, _fresh_pins(proguard, root))
        if drifted:
            return CheckResult(
                name,
                Status.WARN,
                "rules_files drift vs. the lock: "
                + ", ".join(line.split(": ", 1)[1] for line in drifted),
                hint="run `kivyforge lock -p android`; the build refuses drift.",
            )
    count = len(proguard.keep) + len(proguard.rules_files)
    return CheckResult(
        name,
        Status.PASS,
        f"{len(proguard.keep)} keep rule(s), {len(proguard.rules_files)} rules "
        f"file(s) for {', '.join(shipped)}"
        if count
        else "declared",
    )


def _fresh_pins(proguard: AndroidProguardConfig, root: Path) -> list[LockedRulesFile]:
    try:
        return hash_pins(proguard, root)
    except ProguardError:  # pragma: no cover - FAIL above covers missing files
        return []


def _java_python_may_reach(config: Config) -> list[str]:
    """What the app ships in Java beyond the bootstrap, for the doctor's WARN."""
    android = config.android_required
    shipped: list[str] = []
    if android.src.java or android.src.kotlin:
        shipped.append("src.java/src.kotlin")
    if android.gradle.dependencies:
        shipped.append("gradle dependencies")
    if android.aars or android.jars:
        shipped.append("native.aars/native.jars")
    return shipped
